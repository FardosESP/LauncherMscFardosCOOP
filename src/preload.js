const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  getState: (gameDir) => ipcRenderer.invoke('state:get', gameDir),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  pickGameDir: () => ipcRenderer.invoke('game:pick'),
  autoDetect: () => ipcRenderer.invoke('game:autodetect'),
  installLoader: (gameDir) => ipcRenderer.invoke('loader:install', gameDir),
  installTailscale: () => ipcRenderer.invoke('tailscale:install'),
  openFirewall: (port) => ipcRenderer.invoke('firewall:open', port),
  onUpdateStatus: (cb) => ipcRenderer.on('update:status', (_e, s) => cb(s)),
  onUpdateState: (cb) => ipcRenderer.on('update:state', (_e, s) => cb(s)),
  checkUpdates: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  setAutoInstall: (value) => ipcRenderer.invoke('update:auto', value),
  getAutoInstall: () => ipcRenderer.invoke('update:autoGet'),
  onGameStatus: (cb) => ipcRenderer.on('game:status', (_e, s) => cb(s)),
  restoreBackup: (gameDir) => ipcRenderer.invoke('backup:restore', gameDir),
  runDiagnostics: (gameDir) => ipcRenderer.invoke('diag:run', gameDir),
  checkRequirements: (gameDir) => ipcRenderer.invoke('req:check', gameDir),
  setLogsConsent: (value) => ipcRenderer.invoke('logs:consent', value),
  openLogsFolder: () => ipcRenderer.invoke('logs:open'),
  pickSharedFolder: () => ipcRenderer.invoke('share:pick'),
  setShareLogs: (value) => ipcRenderer.invoke('share:set', value),
  getShareLogs: () => ipcRenderer.invoke('share:get'),
  onShareState: (cb) => ipcRenderer.on('share:state', (_e, s) => cb(s)),
  stopShare: () => ipcRenderer.invoke('share:stop'),
  showReport: (p) => ipcRenderer.invoke('diag:show', p),
  openTailscale: () => ipcRenderer.invoke('tailscale:open'),
  openTailscaleKeys: () => ipcRenderer.invoke('tailscale:keys'),
  tailscaleStatus: () => ipcRenderer.invoke('tailscale:status'),
  tailscalePing: (ip) => ipcRenderer.invoke('tailscale:ping', ip),
  loginTailscale: (key) => ipcRenderer.invoke('tailscale:login', key),
  openModsFolder: () => ipcRenderer.invoke('mods:open'),
  copyText: (text) => ipcRenderer.invoke('clipboard:write', text),
  launch: (payload) => ipcRenderer.invoke('game:launch', payload),
});
